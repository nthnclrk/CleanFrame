"""Generate app/legacy-chromium.css: spacing fallbacks for pre-2020 TV engines.

CleanFrame's stylesheet uses flex `gap` (Chrome 84) and `inset` (Chrome 87). A 2019
Samsung runs Chromium 63, which does not recognise either, drops the declaration and
renders the layout with no spacing at all.

This reads app/style.css and emits the equivalent as margins and offsets, wrapped in
`@supports not (...)` so it applies only where the modern property is missing. Nothing
in style.css changes, so the file stays identical to upstream and rebases cleanly.

Flex direction decides which margin stands in for a gap, so it is resolved from the
same rule, then from the base rule the selector extends, and defaults to `row` as flex
does. DIRECTION_OVERRIDES records the cases confirmed against a real browser's computed
styles where the stylesheet alone is ambiguous.

Read-only apart from its output. Usage: python -I scripts/build-legacy-css.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "app/style.css"
TARGET = ROOT / "app/legacy-chromium.css"

# Confirmed in a browser against the live DOM; the stylesheet alone does not say.
DIRECTION_OVERRIDES = {
    ".l-list .quiet-utils .u-content": "row-reverse",
    '.l-list .quiet-utils .u[data-action="util.settings"] .u-content': "row-reverse",
    ".l-list .quiet-utils.is-text .u-content": "row-reverse",
}

MARGIN_FOR = {
    "row": "margin-left",
    "row-reverse": "margin-right",
    "column": "margin-top",
    "column-reverse": "margin-bottom",
}

RULE = re.compile(r"([^{}]+)\{([^{}]*)\}", re.S)


def rules(css):
    for match in RULE.finditer(css):
        yield " ".join(match.group(1).split()), match.group(2)


def main():
    css = re.sub(r"/\*.*?\*/", "", SOURCE.read_text(encoding="utf-8"), flags=re.S)

    # Every flex-direction in the file, so a gap rule can inherit its container's.
    directions = {}
    for selector, body in rules(css):
        found = re.search(r"flex-direction\s*:\s*([^;]+)", body)
        if found:
            directions[selector] = found.group(1).strip()

    # Elements style.css pushes to the far end of their row with an auto margin. A gap
    # margin would overwrite that - and wins, because a descendant selector like
    # ".er-name .panel-content > * + *" outranks a single class. Re-asserting the auto
    # afterwards cannot win either, so they are excluded from the gap margin instead.
    # An auto margin already absorbs the free space, so it lands where the gap left it.
    autos = []
    for selector, body in rules(css):
        if re.search(r"margin(-(?:left|right|top|bottom))?\s*:[^;}]*\bauto\b", body):
            autos.append(selector.strip())
    # :not() takes only a simple selector on these engines, so keep the plain classes.
    exclude = sorted({s for s in autos if re.fullmatch(r"\.[A-Za-z0-9_-]+", s)})
    skip = "".join(f":not({s})" for s in exclude)

    gaps, insets = [], []
    for selector, body in rules(css):
        gap = re.search(r"(?<![-\w])gap\s*:\s*([^;]+)", body)
        if gap:
            direction = (
                DIRECTION_OVERRIDES.get(selector)
                or directions.get(selector)
                # A compound selector such as ".is-horizontal .setting-options"
                # inherits from the plain ".setting-options" rule.
                or directions.get("." + selector.rsplit(".", 1)[-1].split()[-1])
                or "row"
            )
            gaps.append((selector, gap.group(1).strip(), direction))
        if re.search(r"(?<![-\w])inset\s*:\s*0(\w*)?\s*(;|$)", body):
            insets.append(selector)

    out = [
        "/* Generated by scripts/build-legacy-css.py - do not edit by hand.",
        " *",
        " * Spacing for TV engines without flex `gap` (Chrome 84) or `inset` (Chrome 87),",
        " * such as the Chromium 63 in a 2019 Samsung on Tizen 5.0. Each block applies only",
        " * where the modern property is unsupported, so newer engines are untouched.",
        " *",
        " * Link this AFTER style.css: a real `gap` beats any margin set earlier, so the",
        " * stand-in margins must too. Loading it first let `.setting-tick{margin-left:0}`",
        " * swallow a 16px gap. Elements style.css aligns with an auto margin are skipped,",
        " * since a gap margin would pin them back beside their neighbour.",
        " */",
        "",
        "@supports not (gap: 1px) {",
    ]
    for selector, value, direction in gaps:
        prop = MARGIN_FOR[direction]
        # A real `gap` replaces whatever a less specific rule set, on both axes. Margins
        # do not, so the unused axis is zeroed too: without this, ".setting-options"
        # (column, 4px) kept adding 4px of vertical space inside the horizontal
        # ".is-horizontal .setting-options" (row, 12px) that overrides it.
        other = "margin-top" if prop in ("margin-left", "margin-right") else "margin-left"
        # "a, b" needs the child combinator on each part, not just the last one.
        targets = ", ".join(part.strip() + " > * + *" + skip for part in selector.split(","))
        out.append(f"  {targets} {{ {prop}: {value}; {other}: 0; }}")
    out.append("}")
    out.append("")

    # A selector list is dropped whole when one part is unknown, so the focus ring
    # vanishes on engines without :focus-visible (Chrome 86). The TV is remote-only,
    # with no pointer to distinguish, so plain :focus is the same thing there.
    focus = [(sel, body) for sel, body in rules(css) if ":focus-visible" in sel]
    if focus:
        out.append("/* :focus-visible (Chrome 86) as plain :focus; a TV has no pointer. */")
        out.append("@supports not (gap: 1px) {")
        for selector, body in focus:
            plain = selector.replace(":focus-visible", ":focus")
            out.append(f"  {plain} {{{' '.join(body.split())}}}")
        out.append("}")
        out.append("")

    out.append("@supports not (inset: 0) {")
    for selector in insets:
        out.append(f"  {selector} {{ top: 0; right: 0; bottom: 0; left: 0; }}")
    out.append("}")
    out.append("")

    TARGET.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(gaps)} gap rules, {len(insets)} inset rules -> {TARGET.relative_to(ROOT)}")
    for selector, value, direction in gaps:
        if direction != "row":
            print(f"  {direction:14} {selector}  ({value})")


if __name__ == "__main__":
    main()
